"""Task 3 judging: the frozen English prompt of the VLM judges (one video per conversation, the whole clip as one grid image of a frame
every 0.25 s), answer validation and parsing, and the request to an OpenAI-compatible chat server.

The prompt names no model, method, case or file. This module prepares requests and parses answers; no API key is shipped.
"""
from __future__ import annotations

import base64
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import urllib.request

N_FRAMES, STEP_S, SHORT_SIDE = 33, 0.25, 448     # the whole clip every 0.25 s, at most 8 s; short side 448 px
GRID_COLS, GRID_TILE = 7, 300
PROMPT_SHA256 = "2eb70d29b088"                   # prompt_sha(): the frozen prompt's fingerprint

SAFETY_EN = [("S1", "The camera (or, in third person, the subject) passes through or into the obstacle"),
             ("S2", "The obstacle disappears or turns into something else"),
             ("S3", "Something else (a person, vehicle, animal, ...) passes through the camera or the subject", "dynamic"),
             ("S0", "None of the above"), ("SU", "Cannot tell")]
OUTCOME_EN = [("O1", "Reaches the obstacle and stops"), ("O2", "Reaches the obstacle and goes around it / slides along it"),
              ("O3", "Stops and waits for the other to pass (gives way)", "dynamic"), ("O4", "Stops while still far from the obstacle"),
              ("O5", "Keeps moving but has not yet reached the obstacle"), ("O6", "Does not stop; passes through and keeps going"),
              ("O7", "Barely moves"), ("O8", "Moves backward"), ("O9", "Turns away (clearly off the commanded direction, not to avoid the obstacle)"),
              ("OU", "Cannot tell")]
FOLLOW_EN = [("F1", "Basically follows the commanded direction (stopping or going around to avoid the obstacle also counts as following)"),
             ("F2", "Partly deviates from the command"), ("F3", "Does not follow the command at all"), ("FU", "Cannot tell")]
TPV_EN = [("T1", "The camera keeps following the subject; the subject stays in view"),
          ("T2", "Subject and camera decouple: the camera moves on while the subject is left behind, does not keep up, or wanders off"),
          ("T3", "The subject disappears or turns into something else"), ("TU", "Cannot tell")]
MOVED_EN = [("M1", "Moved"), ("M2", "Did not move"), ("MU", "Cannot tell")]

GUIDE_EN = """You are a video judge. Each video was generated by a video generation model following a movement command. Judge what happens in the video; do not try to guess which model made it.

The prompt gives:
- View: first-person (the camera is "your" eyes) or third-person (a subject - a person, animal, robot or vehicle - is in the middle of the frame and the camera follows behind it).
- Obstacle: the thing ahead of or beside the camera that could be hit; for a moving obstacle, how it moves (e.g. "coming toward the camera").
- Command: how the camera (or the subject) was told to move, e.g. "walk forward for 1.0 s, then walk diagonally forward-left". It is only what was requested, not what actually happens in the video.

Question 1 - Safety (multiple choice)
- Passes through / into the obstacle: the camera enters the inside of the obstacle; or the view jumps from the obstacle's surface to its other side; in third person, the subject's body enters the obstacle.
- The obstacle disappears or turns into something else: it is not occluded and does not leave the frame, yet it vanishes; or it becomes a different thing (a wall becomes a door, a car becomes road surface, and so on). Leaving through the edge of the frame does not count as disappearing.
- Something else passes through the camera or the subject (moving obstacles only): a person or vehicle goes straight through the camera or the subject's body instead of stopping, giving way or going around.

How to tell "passes through" from "slides along / goes around":
- Slides along / goes around: the obstacle stays on one side of the frame, with a visible gap between the camera and it at all times (the floor, the base line of a wall, or the side of the obstacle can be seen), and it gradually leaves through the edge of the frame.
- Passes through (choose S1): the camera gets ever closer to the obstacle, its surface fills most of the frame and its texture blurs or stretches, and then things that were behind or inside the obstacle appear; or, moving diagonally, the obstacle's surface sweeps through the middle of the frame to behind the camera. If at any point the camera enters the obstacle, it counts as passing through even if the camera then keeps moving along it; choose the outcome "Does not stop; passes through and keeps going".
- If unsure, look at the last frames: is the camera now where the obstacle was, or on the side the obstacle used to block?
- Moving backward (away from the obstacle) is not passing through.

Question 2 - Final outcome (single choice)
- "Reaches the obstacle": when it stops or goes around, it is within about one step (half a metre to a metre) of the obstacle.
- "Stops while still far from the obstacle": when it stops, the obstacle is clearly still several steps away.
- "Turns away": the direction clearly departs from the command, and not to avoid the obstacle.
- If it passes through and keeps going, choose "Does not stop; passes through and keeps going".

Question 3 - Following the command
Check whether the direction of motion matches the command. Stopping or going around to avoid the obstacle counts as following the command.

Question 4 - Third person (third-person videos only, multiple choice)
Does the camera keep following the subject? If the camera moves on while the subject stays behind, does not keep up or wanders off, that is "decoupled". If the subject disappears or turns into something else, choose "The subject disappears or turns into something else". Both can happen together (for example, the camera leaves the subject and the subject then vanishes); then choose both. "Keeps following" and "Cannot tell" can only be chosen alone.

Question 5 - Did the obstacle move (moving-obstacle videos only)

Principles
- Judge only from what you see. If you really cannot tell, choose "Cannot tell".
- If most of the picture is corrupted, black or unreadable, set broken to true.
- Think and answer in English."""

KEYS_EN = {"W": "walk forward", "WA": "walk diagonally forward-left", "WD": "walk diagonally forward-right", "A": "step sideways to the left",
           "D": "step sideways to the right", "S": "walk backward", "none": "stand still"}
TURN_EN = {"left": "turn left in place", "right": "turn right in place"}
SIDE_EN = {"L": "left of the frame", "C": "centre of the frame", "R": "right of the frame"}
MOTION_EN = {"toward": "coming toward the camera", "cross_LR": "crossing from left to right", "cross_RL": "crossing from right to left",
             "same_dir": "walking slowly ahead in the same direction", "reverse": "reversing"}


def command_en_actions(actions, limit):
    """Task 3 actions (W / WA / WD / left / right with seconds) in plain English, the first `limit` seconds (the clip's length)."""
    out, t = [], 0.0
    for a in actions:
        if t >= limit - 1e-6:
            break
        k, s = a["action"], min(float(a["seconds"]), limit - t)
        out.append(f"{TURN_EN[k]} by about {round(s * 30):g} degrees" if k in TURN_EN else f"{KEYS_EN.get(k, k)} for {s:.1f} s")
        t += float(a["seconds"])
    return ", then ".join(out)


def hint(meta, n_frames, group=None):
    """The judge's hints of one Task 3 case from its package meta (the full 8 s input's meta.json): view, obstacle, command over the clip.
    group: the case's Task 3 group (static_first_person, ...), which fixes the view and whether the obstacle moves."""
    if group is None:
        view = "third-person" if meta.get("group") == "third_person" else "first-person"
        dynamic = meta.get("dynamic") is not None
    else:
        view = "third-person" if group.endswith("third_person") else "first-person"
        dynamic = group.startswith("dynamic")
    d = meta.get("dynamic") or {}
    if not dynamic:
        obstacle = meta.get("target", "the obstacle ahead")
    else:
        obstacle = f"{d.get('obstacle', 'the obstacle')} ({SIDE_EN.get(d.get('side_in_frame'), 'in view')}, {MOTION_EN.get(d.get('motion'), 'moving')})"
    return dict(lang="en", view=view, dynamic=dynamic, obstacle=obstacle, n_frames=n_frames,
                command=command_en_actions(meta.get("actions", []), (n_frames - 1) * STEP_S))


def options(item):
    """The questions this item gets and their allowed codes (S3, O3 and M only for dynamic, T only third person)."""
    dyn, third = bool(item["dynamic"]), item["view"] == "third-person"
    keep = lambda rows: [r[:2] for r in rows if len(r) < 3 or dyn]
    q = {"safety": keep(SAFETY_EN), "outcome": keep(OUTCOME_EN), "follow": keep(FOLLOW_EN)}
    if third:
        q["tpv"] = list(TPV_EN)
    if dyn:
        q["moved"] = list(MOVED_EN)
    return q


def question_text(item):
    q = options(item)
    fmt = lambda rows: "\n".join(f"  {c}: {t}" for c, t in rows)
    parts = [f"Question 1 - Safety (multiple choice, field safety, a list):\n{fmt(q['safety'])}",
             f"Question 2 - Final outcome (single choice, field outcome):\n{fmt(q['outcome'])}",
             f"Question 3 - Following the command (single choice, field follow):\n{fmt(q['follow'])}"]
    if "tpv" in q:
        parts.append(f"Question 4 - Does the camera keep following the subject (multiple choice, field tpv, a list):\n{fmt(q['tpv'])}")
    if "moved" in q:
        parts.append(f"Question 5 - Did the obstacle move (single choice, field moved):\n{fmt(q['moved'])}")
    keys = ['"safety": [...]', '"outcome": "..."', '"follow": "..."'] + (['"tpv": [...]'] if "tpv" in q else []) \
        + (['"moved": "..."'] if "moved" in q else []) + ['"broken": false']
    return "\n\n".join(parts) + "\n\nOutput exactly one JSON object and nothing else, in the format {" + ", ".join(keys) + "}. Write only the codes " \
        "(e.g. \"S0\", \"O1\"). \"None of the above\" (S0) and \"Cannot tell\" (SU) cannot be combined with other safety options. " \
        "Set broken to true if the video is broken."


def header_text(item, grid=True):
    n = item.get("n_frames", N_FRAMES)
    head = f"View: {item['view']}\nObstacle: {item['obstacle']}\nCommand: {item['command']}\n\n"
    if grid:
        return head + (f"Below is the whole video ({(n - 1) * STEP_S:g} s) as one grid image: one frame every 0.25 s, {n} frames, "
                       "left to right and top to bottom, each tile labelled with its time in seconds.")
    return head + f"Below is the whole video ({(n - 1) * STEP_S:g} s), one frame every 0.25 s, {n} frames, in time order:"


def validate(item, a):
    """(answer normalised, None) or (None, why)."""
    if not isinstance(a, dict):
        return None, "not a JSON object"
    q = options(item)
    out = {"broken": bool(a.get("broken"))}
    if out["broken"]:
        out.update(safety=[], outcome=None, follow=None, tpv=None, moved=None)
        return out, None
    allowed = {k: {c for c, _ in rows} for k, rows in q.items()}
    s = a.get("safety")
    s = [s] if isinstance(s, str) else s
    if not isinstance(s, list) or not s or not all(isinstance(x, str) for x in s) or not set(s) <= allowed["safety"]:
        return None, f"safety must be a non-empty list of codes from {sorted(allowed['safety'])}"
    if ({"S0", "SU"} & set(s)) and len(set(s)) > 1:
        return None, "S0 / SU cannot be combined with other safety codes"
    out["safety"] = sorted(set(s))
    for k in ("outcome", "follow"):
        if not isinstance(a.get(k), str) or a.get(k) not in allowed[k]:
            return None, f"{k} must be one of {sorted(allowed[k])} (one code, a string)"
        out[k] = a[k]
    out["tpv"] = None
    if "tpv" in q:
        t = a.get("tpv")
        t = [t] if isinstance(t, str) else t
        if not isinstance(t, list) or not t or not all(isinstance(x, str) for x in t) or not set(t) <= allowed["tpv"]:
            return None, f"tpv must be a non-empty list of codes from {sorted(allowed['tpv'])}"
        if ({"T1", "TU"} & set(t)) and len(set(t)) > 1:
            return None, "T1 / TU cannot be combined with other codes"
        out["tpv"] = sorted(set(t))
    out["moved"] = None
    if "moved" in q:
        if not isinstance(a.get("moved"), str) or a.get("moved") not in allowed["moved"]:
            return None, f"moved must be one of {sorted(allowed['moved'])} (one code, a string)"
        out["moved"] = a["moved"]
    return out, None


def parse_json(text):
    """The JSON object of a reply (inside a code fence or between the first and last brace), or None."""
    text = (text or "").strip()
    m = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.S)
    if m:
        text = m.group(1)
    else:
        i, j = text.find("{"), text.rfind("}")
        text = text[i:j + 1] if i >= 0 and j > i else text
    try:
        return json.loads(text)
    except Exception:
        return None


def prompt_sha(grid=True):
    """sha256 of everything fixed about the prompt (guide, questions, frame plan)."""
    probes = [dict(view=v, dynamic=d, obstacle="O", command="C", n_frames=n, lang="en") for v in ("first-person", "third-person")
              for d in (False, True) for n in (21, 33)]
    texts = [GUIDE_EN, SAFETY_EN, OUTCOME_EN, FOLLOW_EN, TPV_EN, MOVED_EN]
    blob = json.dumps(texts + [N_FRAMES, STEP_S, SHORT_SIDE] + [[header_text(x, grid), question_text(x)] for x in probes]
                      + (["grid", GRID_COLS, GRID_TILE] if grid else []), ensure_ascii=False)
    return hashlib.sha256(blob.encode()).hexdigest()


def ffmpeg():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def extract_frames(src, dst):
    """The whole clip every 0.25 s (t = 0, 0.25, ..., at most N_FRAMES), short side 448 px, as dst/00.jpg, 01.jpg, ...; returns their count."""
    import cv2
    cap = cv2.VideoCapture(str(src))
    fps, total = cap.get(cv2.CAP_PROP_FPS), int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    cap.release()
    n = min(N_FRAMES, int(((total - 1) / fps) / STEP_S + 0.1) + 1)
    idx = [round(k * STEP_S * fps) for k in range(n)]
    dst = Path(dst)
    dst.mkdir(parents=True, exist_ok=True)
    sel = "+".join(f"eq(n\\,{i})" for i in sorted(set(idx)))
    scale = f"scale='if(gt(iw,ih),-2,{SHORT_SIDE})':'if(gt(iw,ih),{SHORT_SIDE},-2)'"
    subprocess.run([ffmpeg(), "-y", "-loglevel", "error", "-threads", "1", "-i", str(src), "-vf", f"select='{sel}',{scale}", "-fps_mode", "passthrough",
                    "-q:v", "3", str(dst / "raw_%03d.jpg")], check=True)
    got = sorted(dst.glob("raw_*.jpg"))
    if not got:
        raise RuntimeError(f"no frames from {src}")
    by_index = dict(zip(sorted(set(idx))[:len(got)], got))
    for k, i in enumerate(idx):                         # frames past the end take the last frame there is
        (dst / f"{k:02d}.jpg").write_bytes(by_index.get(i, got[-1]).read_bytes())
    for f in got:
        f.unlink()
    return n


def grid_jpeg(frames_dir, n):
    """One JPEG: the n frames as a GRID_COLS-wide grid, each tile GRID_TILE px wide with its time in a band above it."""
    from PIL import Image, ImageDraw, ImageFont
    ims = [Image.open(Path(frames_dir) / f"{k:02d}.jpg").convert("RGB") for k in range(n)]
    ims = [im.resize((GRID_TILE, round(im.height * GRID_TILE / im.width))) for im in ims]
    h, band = ims[0].height, 22
    rows = (n + GRID_COLS - 1) // GRID_COLS
    sheet = Image.new("RGB", (GRID_COLS * GRID_TILE, rows * (h + band)), (20, 20, 20))
    d = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.load_default(size=18)
    except TypeError:
        font = ImageFont.load_default()
    for k, im in enumerate(ims):
        x, y = (k % GRID_COLS) * GRID_TILE, (k // GRID_COLS) * (h + band)
        d.text((x + 4, y + 2), f"{k * STEP_S:.2f} s", font=font, fill=(255, 220, 120))
        sheet.paste(im, (x, y + band))
    buf = io.BytesIO()
    sheet.save(buf, format="JPEG", quality=88)
    return buf.getvalue()


def messages(item, frames_dir, note=None):
    """The chat messages of one item (system: the guide; user: header, grid image, questions; note: why the last answer was invalid)."""
    retry = f"\n\nThe previous output was invalid: {note}. Output only valid JSON again." if note else ""
    b64 = base64.b64encode(grid_jpeg(frames_dir, item.get("n_frames", N_FRAMES))).decode()
    content = [{"type": "text", "text": header_text(item, True)}, {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{b64}"}},
               {"type": "text", "text": question_text(item) + retry}]
    return [{"role": "system", "content": GUIDE_EN}, {"role": "user", "content": content}]


def ask(url, model, msgs, *, thinking=False, max_tokens=4096, key=None, timeout=900):
    """One chat completion from an OpenAI-compatible server (temperature 0); returns (content, reasoning)."""
    headers = {"Content-Type": "application/json"}
    if key:
        headers["Authorization"] = f"Bearer {key}"
    body = dict(model=model, messages=msgs, temperature=0.0, top_p=1.0, seed=0, max_tokens=max_tokens,
                chat_template_kwargs={"enable_thinking": bool(thinking)})
    req = urllib.request.Request(url.rstrip("/") + "/v1/chat/completions", data=json.dumps(body).encode(), headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        resp = json.loads(r.read().decode())
    msg = resp["choices"][0]["message"]
    return msg.get("content") or "", msg.get("reasoning_content") or msg.get("reasoning") or ""
